import fs from "node:fs"
import path from "node:path"
import {fileURLToPath} from "node:url"
import {scopeBlueprintCss} from "../src/blueprint-css.js"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, "..")
const coreCssPath = path.join(rootDir, "node_modules/@blueprintjs/core/lib/css/blueprint.css")
const selectCssPath = path.join(rootDir, "node_modules/@blueprintjs/select/lib/css/blueprint-select.css")
const outPath = path.join(rootDir, "src/blueprint-styles.js")

export function buildBlueprintStylesModule() {
  const coreRaw = fs.readFileSync(coreCssPath, "utf8")
  const selectRaw = fs.readFileSync(selectCssPath, "utf8")

  const coreScoped = scopeBlueprintCss(coreRaw)
  const selectScoped = scopeBlueprintCss(selectRaw)

  return [
    "// Generated by scripts/generate-blueprint-css.mjs from @blueprintjs/core and @blueprintjs/select.",
    "// Excludes normalize.css, @font-face rules, and icon font glyph rules; all rules scoped to .sr-dashboard-blueprint.",
    "",
    `export const BLUEPRINT_CORE_SCOPED_CSS = ${JSON.stringify(coreScoped)}`,
    `export const BLUEPRINT_SELECT_SCOPED_CSS = ${JSON.stringify(selectScoped)}`,
    "export const BLUEPRINT_SCOPED_CSS = `${BLUEPRINT_CORE_SCOPED_CSS}\\n${BLUEPRINT_SELECT_SCOPED_CSS}`",
    "",
  ].join("\n")
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)

if (isMain) {
  const checkOnly = process.argv.includes("--check")
  const generated = buildBlueprintStylesModule()

  if (checkOnly) {
    const existing = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : ""
    if (existing !== generated) {
      console.error("src/blueprint-styles.js is out of date. Run: node scripts/generate-blueprint-css.mjs")
      process.exit(1)
    }
    console.log("src/blueprint-styles.js is up to date.")
  } else {
    fs.writeFileSync(outPath, generated, "utf8")
    console.log(`Wrote ${path.relative(rootDir, outPath)} (${generated.length} bytes)`)
  }
}
